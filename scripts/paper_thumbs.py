#!/usr/bin/env python3
"""Thumbnails and figures for the papers in public/data/publications.json.

Two outputs, both WebP under public/media/research/, both logged in docs/media/THUMBS.md
(one row per file; the review column is written by hand and survives re-runs).

1. Thumbnail (default mode): 1200x750 under 120 KB for every featured paper, the
   `thumbnail` field (the /research grid). Strategy per paper (first that works):
     a. arXiv HTML rendering (https://arxiv.org/html/<id>): the first raster <img> inside a
        <figure> (class ltx_figure / ltx_graphics), at least 500x300 px. Recorded as
        "arXiv HTML figure 1". Skipped with --page.
     b. PDF page 1 (the paper's `pdf` field, or https://arxiv.org/pdf/<id>): rasterized with
        pdftoppm at 150 dpi, top 60% kept (title, authors, usually the teaser figure), then
        fitted to 1200x750 biased towards the top. Recorded as "PDF page 1, top 60%".

2. Figure (--size, landing v5): one main figure of the paper at 1600x1000 (16:10, the same
   ratio as the thumbnails) under 200 KB, the `figure` field (the landing research
   carousel shows it next to the abstract). The figure is chosen by hand:
     --figure n      the figure the paper itself numbers n in its arXiv HTML (the caption
                     tag "Figure n:" or "Fig. n:"); --panel k takes the kth graphic inside it
                     (default 1), --panel 2,3 montages panels side by side. SVG graphics
                     (<object> files or inline TikZ/pgfplots) are rasterized with ImageMagick
     --pdf-page p    render page p of the PDF (--dpi, default 300) instead, for papers
                     without arXiv HTML; --pdf-image k takes the page's kth embedded raster
                     at native resolution instead of rendering (pdfimages -list shows them)
     --crop l,t,r,b  keep this box of the source image, fractions 0..1 (cuts captions, side
                     panels, page margins); recorded in the log so the cut is reproducible
     --cover         fill the 16:10 canvas and crop the overflow instead of letterboxing on
                     paper-50
     --no-trim       keep uniform-colour margins (trimmed by default)
   Page-1 crops are thumbnails, never figures: --page is refused together with --size.
   --list prints the figures the arXiv HTML has (number, id, rasters, caption) to pick from.

Usage:
  python3 scripts/paper_thumbs.py [--only id1,id2] [--force] [--page]
  python3 scripts/paper_thumbs.py --list --only id
  python3 scripts/paper_thumbs.py --size 1600 --figure 3 [--panel 1] [--crop l,t,r,b] [--cover] --only id
  python3 scripts/paper_thumbs.py --size 1600 --pdf-page 4 --crop l,t,r,b --only id
  python3 scripts/paper_thumbs.py --size 1600 --pdf-page 5 --pdf-image 1 --only id
  python3 scripts/paper_thumbs.py --size 1600            # figure 1 for every paper with featured_order
Needs: pdftoppm and pdfimages (poppler-utils), Pillow with WebP support, network access;
SVG figures need Playwright's Chromium (pip install playwright; playwright install chromium)
or ImageMagick as a weaker fallback.
"""
